#!/usr/bin/env python3
"""
Build the compact data files used by the BR Seat Finder extension.

Source: https://github.com/hussain-ahmed2/bd-railway-data
    railway-stations.json  -> 425 stations (code, name en/bn, lat, lng, zone, isMajorJunction)
    railway-data.json      -> 224 trains with ordered stoppages

Outputs (inside ../data):
    stations.js   window.BR_DATA.stations  = [[code, nameEn, nameBn, lat, lng, flags], ...]
    trains.js     window.BR_DATA.trains    = [[code, nameEn, "S1|S2|...", offday], ...]

offday encoding: 0 = daily / unknown, 1..7 = Sunday..Saturday  (the day the train does NOT run)
flags: bit0 = major junction
"""
import json
import os
import re
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")
OUT = os.path.join(HERE, "..", "data")
ALL_TRAINS_URL = "https://railspaapi.shohoz.com/v1.0/web/all-trains/info"

DAYS = {
    "sunday": 1, "monday": 2, "tuesday": 3, "wednesday": 4,
    "thursday": 5, "friday": 6, "saturday": 7,
}


def enc_offday(v):
    s = (v or "").strip().lower()
    if not s or s.startswith("daily") or s.startswith("none"):
        return 0
    return DAYS.get(s, 0)


def js_str(s):
    return json.dumps(s, ensure_ascii=False)


def norm(s):
    s = re.sub(r"\([^)]*\)", " ", str(s or "").lower())
    s = re.sub(r"[^a-z0-9]+", " ", s).strip()
    s = re.sub(r"\b(junction|jn|junc)\b", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def fetch_site_names():
    """Public endpoint: it leaks the exact city names the eticket site uses."""
    cache = os.path.join(RAW, "all-trains-info.json")
    doc = None
    try:
        with urllib.request.urlopen(ALL_TRAINS_URL, timeout=25) as r:
            doc = json.load(r)
        with open(cache, "w", encoding="utf-8") as f:
            json.dump(doc, f, ensure_ascii=False)
    except Exception as exc:                                   # offline / blocked
        print("  ! could not refresh %s (%s)" % (ALL_TRAINS_URL, exc))
        if os.path.exists(cache):
            doc = json.load(open(cache, encoding="utf-8"))
    if not doc:
        return {}
    cities = set()
    for t in doc.get("data", {}).get("trains", []):
        for k in ("origin_city", "destination_city"):
            v = (t.get(k) or "").strip()
            if v:
                cities.add(v.replace("_", " ").strip())
    return sorted(cities)


def main():
    stations = json.load(open(os.path.join(RAW, "railway-stations.json"), encoding="utf-8"))
    trains_doc = json.load(open(os.path.join(RAW, "railway-data.json"), encoding="utf-8"))
    trains = trains_doc["trains"]

    codes = {s["code"] for s in stations}

    # ---------- stations.js ----------
    rows = []
    for s in stations:
        code = s["code"]
        name_en = s["name"]["en"].strip()
        name_bn = (s["name"].get("bn") or "").strip()
        lat = s.get("lat")
        lng = s.get("lng")
        if lat is None or lng is None:
            continue
        flags = 1 if s.get("isMajorJunction") else 0
        rows.append([code, name_en, name_bn, round(float(lat), 5), round(float(lng), 5), flags])

    rows.sort(key=lambda r: r[1].lower())

    with open(os.path.join(OUT, "stations.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_data.py -- do not edit by hand.\n")
        f.write("// Source: github.com/hussain-ahmed2/bd-railway-data (%s)\n"
                % trains_doc.get("meta", {}).get("lastUpdated", ""))
        f.write("// [code, nameEn, nameBn, lat, lng, flags]\n")
        f.write("(function (root) {\n  root.BR_DATA = root.BR_DATA || {};\n")
        f.write("  root.BR_DATA.stationMeta = %s;\n" % json.dumps(
            {"count": len(rows), "source": "bd-railway-data",
             "updated": trains_doc.get("meta", {}).get("lastUpdated", "")}, ensure_ascii=False))
        f.write("  root.BR_DATA.stations = [\n")
        for i, r in enumerate(rows):
            comma = "," if i < len(rows) - 1 else ""
            f.write("    [%s,%s,%s,%s,%s,%d]%s\n"
                    % (js_str(r[0]), js_str(r[1]), js_str(r[2]), r[3], r[4], r[5], comma))
        f.write("  ];\n})(typeof window !== 'undefined' ? window : globalThis);\n")

    # ---------- trains.js ----------
    trows = []
    dropped = 0
    for t in trains:
        stops = [sp["stationCode"] for sp in t.get("stoppages", []) if sp.get("stationCode") in codes]
        if len(stops) < 2:
            dropped += 1
            continue
        trows.append([
            str(t["code"]),
            (t.get("name", {}).get("en") or "").strip(),
            "|".join(stops),
            enc_offday(t.get("offDay", {}).get("en")),
        ])
    trows.sort(key=lambda r: (r[1].lower(), r[0]))

    with open(os.path.join(OUT, "trains.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_data.py -- do not edit by hand.\n")
        f.write("// [trainCode, trainNameEn, 'STA|STB|...' (ordered stops), offday(0=daily,1=Sun..7=Sat)]\n")
        f.write("(function (root) {\n  root.BR_DATA = root.BR_DATA || {};\n")
        f.write("  root.BR_DATA.trains = [\n")
        for i, r in enumerate(trows):
            comma = "," if i < len(trows) - 1 else ""
            f.write("    [%s,%s,%s,%d]%s\n"
                    % (js_str(r[0]), js_str(r[1]), js_str(r[2]), r[3], comma))
        f.write("  ];\n})(typeof window !== 'undefined' ? window : globalThis);\n")

    # ---------- site-names.js ----------
    # Map station code -> the name the eticket site actually accepts.
    cities = fetch_site_names()
    index = {}
    for r in rows:
        for key in {norm(r[1]), norm(re.sub(r"\([^)]*\)", " ", r[1]))}:
            if key:
                index.setdefault(key, []).append(r)

    overrides, unresolved = {}, []
    for c in cities:
        k = norm(c)
        hits = index.get(k)
        if not hits:                       # prefix match, shortest station name wins
            cand = [v for key, v in index.items()
                    if key and (key.startswith(k) or k.startswith(key))]
            if cand:
                hits = sorted(cand, key=lambda v: min(len(x[1]) for x in v))[0]
        if hits:
            best = sorted(hits, key=lambda r: (0 if r[5] & 1 else 1, len(r[1])))[0]
            overrides[best[0]] = c
        else:
            unresolved.append(c)

    with open(os.path.join(OUT, "site-names.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_data.py -- do not edit by hand.\n")
        f.write("// Station code -> the station name the eticket API expects.\n")
        f.write("// Harvested from the public %s endpoint.\n" % ALL_TRAINS_URL)
        f.write("(function (root) {\n  root.BR_DATA = root.BR_DATA || {};\n")
        f.write("  root.BR_DATA.siteNames = %s;\n" % json.dumps(overrides, ensure_ascii=False, indent=2, sort_keys=True))
        f.write("})(typeof window !== 'undefined' ? window : globalThis);\n")

    print("site names harvested: %d (unresolved %d: %s)"
          % (len(overrides), len(unresolved), ", ".join(unresolved) or "-"))

    print("stations: %d" % len(rows))
    print("trains:   %d (dropped %d)" % (len(trows), dropped))
    for p in ("stations.js", "trains.js", "site-names.js"):
        fp = os.path.join(OUT, p)
        print("  %-12s %.1f KB" % (p, os.path.getsize(fp) / 1024.0))


if __name__ == "__main__":
    main()
